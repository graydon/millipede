#!/usr/bin/env bash
# Runs the key-value server of Tests/FormatKVSrv.lean, whose request parser and response serialiser
# are proved against the format descriptions `reqFmt` and `respFmt`, on sample inputs, for x64
# (under qemu-x86_64) and arm64 (natively). Building Tests.FormatKVSrv writes the images
# .lake/kvsrv-x64 and .lake/kvsrv-a64 with `#mp_compile`. The expected output and exit status of
# each input are computed by a reference written here in Python, independently of the Lean model:
# the server answers each request in order and exits 0 at the end of the input, or exits 1 at the
# first malformed request, after the answers to the requests before it.
#   request  = id:u16be op:u8 (op 1 get, 3 delete: key; op 2 put: key value)
#   key      = len:u8 (<= 16) bytes;  value = len:u16be (<= 32) bytes
#   response = id:u16be status:u8 (0: value; 1: nothing; 2: code:u8, 1 store full, 2 no such key)
# The store holds four keys, and the server reads at most 256 bytes. The inputs are 14 written by
# hand and 40 generated from fixed seeds, which are request sequences over a few keys that may end
# in a malformed request. `--selftest` runs the binaries against three wrong references, which
# read lengths little-endian, accept a key or value one byte longer than its bound, or tag a found
# value with the error arm, and requires each of them to disagree with the binaries. The script
# also evaluates the specification `kvTrace` of Tests/KVSpec.lean on every input, delivered in reads
# of 7 bytes, with scripts/kvspec.lean, and requires its writes and exit status to be the reference's.
# Then it runs the batch echo program of Tests/FormatGenProg.lean, whose format is generated by
# `mp format` (Tests/FormatGen.lean), on 9 written and 30 generated inputs on both targets against
# a second Python reference; `--selftest` requires three wrong batch references (the padding byte
# echoed, a count of 4 accepted, a code of 4 bytes) to disagree with both binaries.
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="$HOME/tools/bin:$PATH"
QEMU="${QEMU:-$HOME/tools/bin/qemu-x86_64}"
lake build Tests.FormatKVSrv Tests.KVRefine Tests.FormatGenProg >/dev/null
if [ ! -x .lake/kvsrv-x64 ] || [ ! -x .lake/kvsrv-a64 ]; then
  lake env lean Tests/FormatKVSrv.lean >/dev/null
fi
if [ ! -x .lake/batch-x64 ] || [ ! -x .lake/batch-a64 ]; then
  lake env lean Tests/FormatGenProg.lean >/dev/null
fi
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
fail=0
mode="${1:-}"

cat > "$tmp/ref.py" <<'EOF'
import sys
data = open(sys.argv[1], "rb").read()[:256]
mut = sys.argv[3] if len(sys.argv) > 3 else ""   # the selftest's wrong references
le = mut == "le"
kmax, vmax = (17, 33) if mut == "lenmax" else (16, 32)
store, out, pos, code = {}, bytearray(), 0, 0
def u16(b): return b[0] | b[1] << 8 if le else b[0] << 8 | b[1]
def p16(n): return bytes([n & 255, n >> 8]) if le else bytes([n >> 8, n & 255])
def key(p):
    if p + 1 > len(data): return None
    n = data[p]
    if n > kmax or p + 1 + n > len(data): return None
    return bytes(data[p + 1:p + 1 + n]), p + 1 + n
def val(p):
    if p + 2 > len(data): return None
    n = u16(data[p:p + 2])
    if n > vmax or p + 2 + n > len(data): return None
    return bytes(data[p + 2:p + 2 + n]), p + 2 + n
while pos < len(data):
    if pos + 3 > len(data): code = 1; break
    rid, op = data[pos] << 8 | data[pos + 1], data[pos + 2]
    k = key(pos + 3) if op in (1, 2, 3) else None
    if k is None: code = 1; break
    kb, p = k
    if op == 2:
        v = val(p)
        if v is None: code = 1; break
        vb, p = v
    out += bytes([rid >> 8, rid & 255])
    if op == 1:
        tag = 2 if mut == "wrongarm" else 0
        out += bytes([tag]) + p16(len(store[kb])) + store[kb] if kb in store else bytes([2, 2])
    elif op == 2:
        if kb in store or len(store) < 4: store[kb] = vb; out += bytes([1])
        else: out += bytes([2, 1])
    else:
        if kb in store: del store[kb]; out += bytes([1])
        else: out += bytes([2, 2])
    pos = p
open(sys.argv[2], "wb").write(bytes(out))
print(code)
EOF

cat > "$tmp/gen.py" <<'EOF'
import random, sys
rnd = random.Random(int(sys.argv[2]))
keys = [b"a", b"b", b"c", b"d", b"e", b"0123456789abcdef", b""]
out = bytearray()
size = rnd.choice([40, 120, 250, 300])
while len(out) < size:
    op = rnd.choice([1, 1, 2, 2, 2, 3])
    k = rnd.choice(keys)
    out += bytes([rnd.randrange(256), rnd.randrange(256), op, len(k)]) + k
    if op == 2:
        v = bytes(rnd.randrange(256) for _ in range(rnd.randrange(33)))
        out += bytes([0, len(v)]) + v
end = rnd.randrange(6)   # sometimes end in a malformed request
if end == 1: out += bytes([0, 1, 1, 17]) + b"x" * 17
elif end == 2: out += bytes([0, 1, 2, 1]) + b"k" + bytes([0, 33]) + b"y" * 33
elif end == 3: out += bytes([0, 1, rnd.choice([0, 4, 255])])
elif end == 4: out = out[:rnd.randrange(len(out) + 1)]
open(sys.argv[1], "wb").write(bytes(out))
EOF

# the inputs: valid sequences, and malformed ones (truncated, a length over its bound, an unknown
# operation, a value length one byte longer than the input)
mk() { python3 -c "import sys; sys.stdout.buffer.write(bytes.fromhex(sys.argv[1]))" "$2" > "$tmp/$1"; }
mk empty ""
mk get-missing "0001 01 03 616263"
mk put-get "0001 02 03 616263 0002 7879  0002 01 03 616263"
mk put-del-get "0007 02 01 6b 0000  0008 03 01 6b  0009 01 01 6b  000a 03 01 6b"
mk full "0001 02 01 61 0001 31  0002 02 01 62 0001 32  0003 02 01 63 0001 33  0004 02 01 64 0001 34  0005 02 01 65 0001 35  0006 01 01 63"
mk overwrite "0101 02 02 6b6b 0003 616263  0102 02 02 6b6b 0001 7a  0103 01 02 6b6b"
mk long-key "0001 02 10 30313233343536373839616263646566 0020 3031323334353637383930313233343536373839303132333435363738393031  0002 01 10 30313233343536373839616263646566"
mk trunc-id "00"
mk trunc-key "0001 01 05 6162"
mk key-too-long "0001 01 11 3031323334353637383961626364656667"
mk bad-op "0001 07 01 61"
mk val-short "0001 02 01 61 0003 7879  0002 01 01 61"
mk val-too-long "0001 02 01 61 0021 303132333435363738393031323334353637383930313233343536373839303132"
mk ok-then-bad "0001 02 01 61 0001 31  0002 01 01 61  0003 09"
inputs="empty get-missing put-get put-del-get full overwrite long-key trunc-id trunc-key key-too-long bad-op val-short val-too-long ok-then-bad"
for i in $(seq 1 40); do python3 "$tmp/gen.py" "$tmp/gen$i" "$i"; inputs="$inputs gen$i"; done

run() {  # run <image> <input> <reference flag>; prints a failure line and returns 1 on mismatch
  local img="$1" in="$2" flag="$3" want got rc=0
  want="$(python3 "$tmp/ref.py" "$tmp/$in" "$tmp/$in.want" $flag)"
  if [ "$img" = x64 ]; then "$QEMU" .lake/kvsrv-x64 < "$tmp/$in" > "$tmp/$in.got" || rc=$?
  else .lake/kvsrv-a64 < "$tmp/$in" > "$tmp/$in.got" || rc=$?; fi
  if [ "$rc" != "$want" ]; then echo "format-check: $img < $in: exit $rc, expected $want"; return 1; fi
  if ! cmp -s "$tmp/$in.got" "$tmp/$in.want"; then echo "format-check: $img < $in: wrong output"; return 1; fi
}
n=0
for img in x64 a64; do
  for in in $inputs; do run "$img" "$in" "" || fail=1; n=$((n + 1)); done
done
lake env lean --run scripts/kvspec.lean "$tmp" $inputs
for in in $inputs; do
  want="$(python3 "$tmp/ref.py" "$tmp/$in" "$tmp/$in.want")"
  if [ "$(cat "$tmp/$in.speccode")" != "$want" ] || ! cmp -s "$tmp/$in.spec" "$tmp/$in.want"; then
    echo "format-check: kvTrace < $in disagrees with the reference"; fail=1
  fi
  n=$((n + 1))
done

# The batch format of Tests/FormatGen.lean, generated by `mp format`, run by the program of
# Tests/FormatGenProg.lean, which echoes the canonical bytes of each batch:
#   batch = "MP" ver:u8 pad:u8 (written as 0) sender:4 count:u8 (<= 3) item*count
#   item  = kind:u8 (0: nothing; 1: num:u32le; 2: code:u16be) name: len:u8 (<= 8) bytes
cat > "$tmp/bref.py" <<'EOF'
import sys
data = open(sys.argv[1], "rb").read()[:256]
mut = sys.argv[3] if len(sys.argv) > 3 else ""   # the selftest's wrong references
cmax = 4 if mut == "count4" else 3
out, pos, code = bytearray(), 0, 0
def item(p):
    if p + 1 > len(data): return None
    kind = data[p]; b = bytes([kind]); p += 1
    w = {0: 0, 1: 4, 2: 4 if mut == "code4" else 2}.get(kind)
    if w is None or p + w > len(data): return None
    b += data[p:p + w]; p += w
    if p + 1 > len(data) or data[p] > 8 or p + 1 + data[p] > len(data): return None
    b += data[p:p + 1 + data[p]]
    return b, p + 1 + data[p]
def batch(p):
    if p + 9 > len(data) or data[p:p + 2] != b"MP": return None
    b = bytes(data[p:p + 3]) + (bytes([data[p + 3]]) if mut == "pad" else b"\0") + data[p + 4:p + 8]
    n = data[p + 8]
    if n > cmax: return None
    b += bytes([n]); p += 9
    for _ in range(n):
        r = item(p)
        if r is None: return None
        b += r[0]; p = r[1]
    return b, p
while pos < len(data):
    r = batch(pos)
    if r is None: code = 1; break
    out += r[0]; pos = r[1]
open(sys.argv[2], "wb").write(bytes(out))
print(code)
EOF
cat > "$tmp/bgen.py" <<'EOF'
import random, sys
rnd = random.Random(int(sys.argv[2]))
def rb(n): return bytes(rnd.randrange(256) for _ in range(n))
out = bytearray()
for _ in range(rnd.randrange(1, 5)):
    out += b"MP" + rb(2) + rb(4)
    n = rnd.randrange(4)
    out += bytes([n])
    for _ in range(n):
        k = rnd.randrange(3)
        out += bytes([k]) + (rb(4) if k == 1 else rb(2) if k == 2 else b"")
        nm = rb(rnd.randrange(9))
        out += bytes([len(nm)]) + nm
end = rnd.randrange(7)   # sometimes end in a malformed batch
if end == 1: out += b"MQ" + rb(7)
elif end == 2: out += b"MP" + rb(6) + bytes([4])
elif end == 3: out += b"MP" + rb(6) + bytes([1, 3, 0])
elif end == 4: out += b"MP" + rb(6) + bytes([1, 0, 9]) + rb(9)
elif end == 5: out = out[:rnd.randrange(len(out) + 1)]
open(sys.argv[1], "wb").write(bytes(out))
EOF
bmk() { python3 -c "import sys; sys.stdout.buffer.write(bytes.fromhex(sys.argv[1]))" "$2" > "$tmp/$1"; }
bmk b-empty ""
bmk b-none "4d50 01 07 61626364 00"
bmk b-three "4d50 02 ff 00010203 03  00 01 61  01 78563412 00  02 0102 02 6869"
bmk b-two "4d50 01 00 41424344 01 02 beef 00  4d50 02 00 45464748 00"
bmk b-magic "4d51 01 00 41424344 00"
bmk b-count "4d50 01 00 41424344 04 00 00 00 00 00 00 00 00"
bmk b-kind "4d50 01 00 41424344 01 03 00"
bmk b-name "4d50 01 00 41424344 01 00 09 616263646566676869"
bmk b-trunc "4d50 01 00 41424344 01 01 7856"
binputs="b-empty b-none b-three b-two b-magic b-count b-kind b-name b-trunc"
for i in $(seq 1 30); do python3 "$tmp/bgen.py" "$tmp/bgen$i" "$i"; binputs="$binputs bgen$i"; done
brun() {  # brun <image> <input> <reference flag>
  local img="$1" in="$2" flag="$3" want rc=0
  want="$(python3 "$tmp/bref.py" "$tmp/$in" "$tmp/$in.want" $flag)"
  if [ "$img" = x64 ]; then "$QEMU" .lake/batch-x64 < "$tmp/$in" > "$tmp/$in.got" || rc=$?
  else .lake/batch-a64 < "$tmp/$in" > "$tmp/$in.got" || rc=$?; fi
  if [ "$rc" != "$want" ]; then echo "format-check: batch $img < $in: exit $rc, expected $want"; return 1; fi
  if ! cmp -s "$tmp/$in.got" "$tmp/$in.want"; then echo "format-check: batch $img < $in: wrong output"; return 1; fi
}
for img in x64 a64; do
  for in in $binputs; do brun "$img" "$in" "" || fail=1; n=$((n + 1)); done
done
if [ "$mode" = "--selftest" ]; then
  for img in x64 a64; do
    for m in le lenmax wrongarm; do
      caught=""
      for in in $inputs; do
        if ! run "$img" "$in" "$m" >/dev/null; then caught="$in"; break; fi
      done
      if [ -z "$caught" ]; then
        echo "format-check: selftest: the wrong reference $m was accepted ($img)"; fail=1
      else echo "format-check: selftest: the wrong reference $m is caught by $caught ($img)"; fi
    done
  done
  for img in x64 a64; do
    for m in pad count4 code4; do
      caught=""
      for in in $binputs; do
        if ! brun "$img" "$in" "$m" >/dev/null; then caught="$in"; break; fi
      done
      if [ -z "$caught" ]; then
        echo "format-check: selftest: the wrong batch reference $m was accepted ($img)"; fail=1
      else echo "format-check: selftest: the wrong batch reference $m is caught by $caught ($img)"; fi
    done
  done
  [ "$fail" = 0 ] && echo "format-check: selftest OK"
fi
if [ "$fail" != 0 ]; then echo "format-check: FAILED"; exit 1; fi
echo "format-check: $n runs (both binaries of both programs, and kvTrace) agree with the references"
